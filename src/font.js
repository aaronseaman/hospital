function compile(src, w, h) {
  const out = {};
  for (const ch in src) {
    const rows = src[ch].split(' ');
    const px = [];
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) if (rows[y] && rows[y][x] === '1') px.push(x, y);
    out[ch] = px;
  }
  return out;
}

export const FONTS = {
  big: { w: 5, h: 7, adv: 6, glyphs: compile(BIG_SRC, 5, 7) },
  small: { w: 3, h: 5, adv: 4, glyphs: compile(SMALL_SRC, 3, 5) },
};

const cache = new Map();
let cacheSize = 0;

function mkCanvas(w, h) {
  const c = document.createElement('canvas');
  c.width = Math.max(1, w);
  c.height = Math.max(1, h);
  return c;
}

export function measureText(text, opts = {}) {
  const f = FONTS[opts.font || 'big'];
  const s = opts.scale || 1;
  const n = String(text).length;
  return { w: n ? (n * f.adv - (f.adv - f.w)) * s : 0, h: f.h * s };
}

function renderString(text, opts) {
  const f = FONTS[opts.font || 'big'];
  const s = opts.scale || 1;
  const str = String(text).toUpperCase();
  const pad = opts.outline ? 1 : 0;
  const shadow = opts.shadow ? 1 : 0;
  const { w, h } = measureText(str, opts);
  const c = mkCanvas(w + pad * 2 + shadow, h + pad * 2 + shadow);
  const g = c.getContext('2d');
  const grad = opts.gradient;
  const plot = (ox, oy, color, useGrad) => {
    for (let i = 0; i < str.length; i++) {
      const px = f.glyphs[str[i]] || f.glyphs['?'];
      const bx = ox + i * f.adv * s;
      for (let k = 0; k < px.length; k += 2) {
        const gy = px[k + 1];
        g.fillStyle = useGrad && grad ? grad[Math.min(grad.length - 1, Math.floor((gy / f.h) * grad.length))] : color;
        g.fillRect(bx + px[k] * s, oy + gy * s, s, s);
      }
    }
  };
  if (opts.shadow) plot(pad + 1, pad + 1, opts.shadow, false);
  if (opts.outline) {
    for (let dy = -1; dy <= 1; dy++)
      for (let dx = -1; dx <= 1; dx++) if (dx || dy) plot(pad + dx, pad + dy, opts.outline, false);
  }
  plot(pad, pad, opts.color || '#fff', true);
  return { c, pad };
}

// Draw text with its top-left at (x, y). opts: {font, color, scale, align, outline, shadow, gradient, alpha}
export function drawText(ctx, text, x, y, opts = {}) {
  if (text === undefined || text === null || text === '') return 0;
  const key = `${text}|${opts.font || 'big'}|${opts.color || '#fff'}|${opts.scale || 1}|${opts.outline || ''}|${opts.shadow || ''}|${opts.gradient ? opts.gradient.join(',') : ''}`;
  let r = cache.get(key);
  if (!r) {
    r = renderString(text, opts);
    cache.set(key, r);
    if (++cacheSize > 800) {
      cache.clear();
      cacheSize = 0;
    }
  }
  const w = r.c.width - r.pad * 2 - (opts.shadow ? 1 : 0);
  let dx = x;
  if (opts.align === 'center') dx = x - Math.floor(w / 2);
  else if (opts.align === 'right') dx = x - w;
  if (opts.alpha !== undefined && opts.alpha < 1) {
    const a = ctx.globalAlpha;
    ctx.globalAlpha = a * Math.max(0, opts.alpha);
    ctx.drawImage(r.c, Math.round(dx - r.pad), Math.round(y - r.pad));
    ctx.globalAlpha = a;
  } else {
    ctx.drawImage(r.c, Math.round(dx - r.pad), Math.round(y - r.pad));
  }
  return w;
}

// Word-wrap text to a max pixel width. Returns array of lines.
export function wrapText(text, maxW, opts = {}) {
  const f = FONTS[opts.font || 'big'];
  const s = opts.scale || 1;
  const maxChars = Math.max(1, Math.floor((maxW + (f.adv - f.w) * s) / (f.adv * s)));
  const out = [];
  for (const para of String(text).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (t.length > maxChars && line) {
        out.push(line);
        line = word;
      } else line = t;
    }
    out.push(line);
  }
  return out;
}
